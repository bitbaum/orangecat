import type { MarkDefinition, MarkShape } from '@/config/marks/types';

/**
 * The TypeScript source the importer writes: one mark module, and the
 * registry index that lists every module in src/config/marks/. Pure string
 * builders, so the exact output is tested rather than trusted.
 */

const quote = (value: string) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** `geo-kit` → `geoKit`; a leading digit gets an underscore. */
export function markIdentifier(slug: string): string {
  const camel = slug.replace(/[-_]+([a-z0-9])/g, (_, c: string) => c.toUpperCase());
  return /^[0-9]/.test(camel) ? `_${camel}` : camel;
}

const objectKey = (slug: string) => (/^[A-Za-z_$][\w$]*$/.test(slug) ? slug : quote(slug));

function shapeSource(shape: MarkShape): string {
  const fields: string[] = [`paint: ${quote(shape.paint)}`];
  if (shape.strokeWidth !== undefined) fields.push(`strokeWidth: ${shape.strokeWidth}`);
  if (shape.linecap) fields.push(`linecap: ${quote(shape.linecap)}`);
  if (shape.linejoin) fields.push(`linejoin: ${quote(shape.linejoin)}`);
  if (shape.fillRule) fields.push(`fillRule: ${quote(shape.fillRule)}`);
  if (shape.opacity !== undefined) fields.push(`opacity: ${shape.opacity}`);
  return `    {\n      ${fields.join(',\n      ')},\n      d: ${quote(shape.d)},\n    },`;
}

export function markModuleSource(
  mark: MarkDefinition,
  origin: { file: string; date: string }
): string {
  return `/**
 * ${mark.name}'s mark. Imported from ${origin.file} on ${origin.date} by
 * \`pnpm run brand:import\`. Do not edit the geometry by hand: change the
 * drawing and import it again.
 *
 *   pnpm run brand:import ${mark.slug} path/to/new-mark.svg
 */

import type { MarkDefinition } from './types';

const mark: MarkDefinition = {
  slug: ${quote(mark.slug)},
  name: ${quote(mark.name)},
  source: ${quote(mark.source)},
  viewBox: [${mark.viewBox.join(', ')}],
  strokeWidth: ${mark.strokeWidth},
  motion: ${quote(mark.motion)},
  shapes: [
${mark.shapes.map(shapeSource).join('\n')}
  ],
};

export default mark;
`;
}

export function marksIndexSource(slugs: readonly string[]): string {
  const sorted = [...slugs].sort((a, b) => a.localeCompare(b, 'en'));
  const imports = sorted.map(s => `import ${markIdentifier(s)} from './${s}';`).join('\n');
  const entries = sorted
    .map(s => {
      const id = markIdentifier(s);
      return objectKey(s) === id ? `  ${id},` : `  ${objectKey(s)}: ${id},`;
    })
    .join('\n');
  return `/**
 * Every mark, by fleet slug. GENERATED by \`pnpm run brand:import\` from the
 * files in this folder — do not edit by hand; add or replace a mark file with
 * the import command and this index follows.
 */

${imports}
import type { MarkDefinition } from './types';

export const MARKS = {
${entries}
} satisfies Record<string, MarkDefinition>;

export type MarkSlug = keyof typeof MARKS;

/** The mark for a fleet slug, or null when that project has none yet. */
export function markFor(slug: string): MarkDefinition | null {
  return (MARKS as Record<string, MarkDefinition>)[slug] ?? null;
}
`;
}
