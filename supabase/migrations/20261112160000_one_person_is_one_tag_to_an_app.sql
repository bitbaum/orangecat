-- One person is one tag to an app (ADR-0014 D7).
--
-- A person can hold several identities, and each is a separate account. An app
-- that gives every account a vote (Solon) therefore gives one person several.
-- To refuse the second seat, the app has to learn that two accounts are one
-- person, and it must learn nothing else: not who the person is, not which
-- other identities they hold, and nothing it could match against another app
-- or another organisation.
--
-- So the app asks for a TAG per account. Two accounts get the same tag exactly
-- when one person holds both. The tag is
--   HMAC-SHA256(key, client_id || scope || holder)
-- so it differs per app (two apps cannot compare notes) and per scope the app
-- names (one organisation's tags say nothing about another's), and without the
-- key it cannot be computed or reversed.
--
-- THE KEY LIVES HERE, generated by the database when this file is applied. It
-- is never in the repository, an environment file or a deploy log, and it is
-- backed up with the data it protects. It does not leave the database: the
-- function below does the keyed step, so the application never holds it.
-- Rotating it would silently unmatch every tag an app has stored, so there is
-- one row and it is written once.
--
-- Rollback: DROP FUNCTION public.identity_person_tags(text, text, uuid[]);
--           DROP TABLE public.identity_person_tag_key;

CREATE TABLE IF NOT EXISTS public.identity_person_tag_key (
  id   integer PRIMARY KEY DEFAULT 1,
  key  bytea NOT NULL DEFAULT extensions.gen_random_bytes(32),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT identity_person_tag_key_is_one_row CHECK (id = 1),
  CONSTRAINT identity_person_tag_key_is_256_bits CHECK (octet_length(key) = 32)
);

ALTER TABLE public.identity_person_tag_key ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.identity_person_tag_key FROM PUBLIC, anon, authenticated, service_role;

INSERT INTO public.identity_person_tag_key (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

CREATE OR REPLACE FUNCTION public.identity_person_tag_key_is_written_once()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  RAISE EXCEPTION 'the person-tag key is written once; changing it unmatches every stored tag'
    USING ERRCODE = 'check_violation';
END;
$$;

DROP TRIGGER IF EXISTS identity_person_tag_key_is_written_once ON public.identity_person_tag_key;
CREATE TRIGGER identity_person_tag_key_is_written_once
  BEFORE UPDATE OR DELETE ON public.identity_person_tag_key
  FOR EACH ROW EXECUTE FUNCTION public.identity_person_tag_key_is_written_once();

COMMENT ON TABLE public.identity_person_tag_key IS
  'The key behind person tags (ADR-0014 D7). One row, written once, readable by no API role: only identity_person_tags() uses it.';

-- The tag for each of the given actors, for one app and one scope. An actor
-- that is not a person's own account (a group's, a placeholder's, or an id
-- OrangeCat does not know) gets no row: the app must read "no tag" as "cannot
-- be told apart", never as "a different person".
CREATE OR REPLACE FUNCTION public.identity_person_tags(
  p_client_id text,
  p_scope     text,
  p_actor_ids uuid[]
)
RETURNS TABLE (actor_id uuid, tag text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT a.id,
         encode(
           extensions.hmac(
             -- Length-prefixed, so ("ab","c") and ("a","bc") can never collide.
             convert_to(
               length(p_client_id)::text || ':' || p_client_id || '|' ||
               length(p_scope)::text     || ':' || p_scope     || '|' ||
               COALESCE(l.holder_user_id, a.user_id)::text,
               'UTF8'
             ),
             k.key,
             'sha256'
           ),
           'hex'
         )
    FROM public.actors a
    CROSS JOIN public.identity_person_tag_key k
    LEFT JOIN public.identity_links l ON l.identity_user_id = a.user_id
   WHERE a.id = ANY (p_actor_ids)
     AND a.actor_type = 'user'
     AND a.user_id IS NOT NULL
     AND p_client_id <> ''
     AND p_scope <> ''
$$;

REVOKE ALL ON FUNCTION public.identity_person_tags(text, text, uuid[]) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.identity_person_tags(text, text, uuid[]) TO service_role;

COMMENT ON FUNCTION public.identity_person_tags(text, text, uuid[]) IS
  'Person tags for an app and a scope (ADR-0014 D7): equal exactly when one person holds both accounts. Service role only; the route that calls it authenticates the app.';
